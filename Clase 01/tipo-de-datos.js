// TIPOS DE DATOS EN JAVASCRIPT

console.log("===== EJEMPLOS SOLICITADOS =====");

// 42
console.log("42 ->", typeof 42);

// 'Veinticinco'
console.log("'Veinticinco' ->", typeof 'Veinticinco');

// -666
console.log("-666 ->", typeof -666);

// true
console.log("true ->", typeof true);

// 0
console.log("0 ->", typeof 0);

// ''
console.log("'' ->", typeof '');

// null
console.log("null ->", typeof null);

// undefined
console.log("undefined ->", typeof undefined);

// FALSE (como texto porque FALSE sin comillas genera error)
console.log("'FALSE' ->", typeof 'FALSE');


console.log("\n===== EJEMPLOS EXTRA =====");

// decimal
console.log("3.1416 ->", typeof 3.1416);

// arreglo
console.log("[1,2,3] ->", typeof [1,2,3]);

// objeto
console.log("{nombre:'Marcos'} ->", typeof {nombre:'Marcos'});

// función
console.log("function(){} ->", typeof function(){});

// NaN
console.log("NaN ->", typeof NaN);

// BigInt
console.log("123n ->", typeof 123n);

// Symbol
console.log("Symbol() ->", typeof Symbol());

// boolean false
console.log("false ->", typeof false);